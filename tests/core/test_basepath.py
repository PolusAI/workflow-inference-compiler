"""`--basepath` and `Workflow.run(basepath=)` are one setting: where Sophios writes what it generates."""
import json
from pathlib import Path
from types import SimpleNamespace
from typing import Final

import pytest

import sophios.plugins
from sophios import main, preflight, run_local
from sophios.api.python import _workflow_runtime as python_runtime
from sophios.api.python.workflow import Step, Workflow

TOOL: Final = 'cwlVersion: v1.2\nclass: CommandLineTool\nbaseCommand: echo\ninputs: {}\noutputs: {}\n'
WORKFLOW: Final = 'steps:\n- id: noop\n'


@pytest.fixture(name='project')
def _project(monkeypatch: pytest.MonkeyPatch, tmp_path: Path) -> Path:
    """A working directory holding the tool `noop`, the workflow `w.wic` that calls it and a config that
    searches the directory. Nothing is pulled, and the runner command is captured instead of written."""
    root = tmp_path / 'project'
    root.mkdir()
    (root / 'noop.cwl').write_text(TOOL, encoding='utf-8')
    (root / 'w.wic').write_text(WORKFLOW, encoding='utf-8')
    (root / 'config.json').write_text(json.dumps({'search_paths_cwl': {'global': [str(root)]},
                                                  'search_paths_wic': {'global': [str(root)]}}), encoding='utf-8')
    monkeypatch.setattr(preflight, 'prepare', lambda *_a, **_k: None)
    monkeypatch.chdir(root)
    return root


def _sophios(monkeypatch: pytest.MonkeyPatch, *flags: str) -> None:
    """`sophios --yaml w.wic --config_file config.json <flags>`, from the working directory."""
    monkeypatch.setattr('sys.argv', ['sophios', '--yaml', 'w.wic', '--config_file', 'config.json', *flags])
    main.main()


def _files(base: Path) -> set[str]:
    return {path.relative_to(base).as_posix() for path in base.rglob('*') if path.is_file()}


@pytest.mark.fast
@pytest.mark.parametrize('spelled', ['out/generated', 'absolute'])
@pytest.mark.parametrize('mode', ['--generate_cwl_workflow', '--generate_run_script'])
def test_the_cli_writes_under_the_basepath_and_nowhere_else(
        project: Path, monkeypatch: pytest.MonkeyPatch, spelled: str, mode: str) -> None:
    """The compiled workflow and job file are under `--basepath`, relative to the working directory or absolute;
    the run script names it for every path the run writes; no `autogenerated/` appears."""
    base = project / 'out' / 'generated'
    cmdlines: list[str] = []
    monkeypatch.setattr(run_local, 'generate_run_script', cmdlines.append)
    _sophios(monkeypatch, mode, '--basepath', str(base) if spelled == 'absolute' else spelled)
    assert {'w.cwl', 'w_inputs.yml'} <= _files(base)
    assert not (project / 'autogenerated').exists()
    if mode == '--generate_run_script':
        resolved = str(base.resolve())
        assert all(resolved in cmdline for cmdline in cmdlines) and len(cmdlines) == 1
        assert f'--provenance {Path(resolved, "provenance", "w")}' in cmdlines[0]


@pytest.mark.fast
def test_the_cli_draws_under_the_basepath(project: Path, monkeypatch: pytest.MonkeyPatch) -> None:
    """`--graphviz` writes its drawings beside the compiled workflow, and names the same directory to `dot`."""
    commands: list[list[str]] = []

    def run(command: list[str], *_args: object, **_kwargs: object) -> SimpleNamespace:
        commands.append(command)
        return SimpleNamespace(stdout=b'')

    monkeypatch.setattr(main.shutil, 'which', lambda _name: '/usr/bin/dot')
    monkeypatch.setattr(main, 'sub', SimpleNamespace(run=run))
    _sophios(monkeypatch, '--generate_cwl_workflow', '--graphviz', '--basepath', 'out')
    assert (project / 'out' / 'w.wic.gv').is_file() and not (project / 'autogenerated').exists()
    assert len(commands) == 3 and all(any(str(Path('out', 'w')) in arg for arg in command) for command in commands)


@pytest.mark.fast
def test_generate_schemas_follows_the_basepath(project: Path, monkeypatch: pytest.MonkeyPatch) -> None:
    """The schema is something Sophios generates: it goes under the base path like the rest."""
    monkeypatch.setattr('sys.argv', ['sophios', '--generate_schemas', '--basepath', 'out'])
    with pytest.raises(SystemExit) as caught:
        main.main()
    assert caught.value.code == 0
    assert (project / 'out' / 'schemas' / 'wic.json').is_file() and not (project / 'autogenerated').exists()


@pytest.mark.fast
def test_a_basepath_that_cannot_be_written_is_wic021_naming_the_flag(
        project: Path, monkeypatch: pytest.MonkeyPatch, capsys: pytest.CaptureFixture[str]) -> None:
    """A file where the directory should be: the message names the path given and tells the user to change it."""
    (project / 'taken').write_text('', encoding='utf-8')
    with pytest.raises(SystemExit) as caught:
        _sophios(monkeypatch, '--generate_cwl_workflow', '--basepath', 'taken')
    assert caught.value.code == 1
    printed = capsys.readouterr().err
    assert 'error [wic021] Sophios writes the compiled workflow to' in printed
    assert str(project / 'taken') in printed and 'give --basepath a directory you can write to' in printed


@pytest.mark.fast
def test_what_the_cli_generates_under_a_search_path_is_not_read_as_a_tool(
        project: Path, monkeypatch: pytest.MonkeyPatch) -> None:
    """A base path below a search path is generated output, so a second run, and a scan from Python given the
    same base path, find only the tool and the workflow that are there."""
    _sophios(monkeypatch, '--generate_cwl_workflow', '--basepath', 'out')
    _sophios(monkeypatch, '--generate_cwl_workflow', '--basepath', 'out')
    assert (project / 'out' / 'w.cwl').is_file()
    config = json.loads((project / 'config.json').read_text(encoding='utf-8'))
    assert [key.stem for key in sophios.plugins.get_tools_cwl(config, basepath='out')] == ['noop']
    assert sorted(sophios.plugins.get_yml_paths(config, basepath=project / 'out')['global']) == ['w']
    assert 'w' in [key.stem for key in sophios.plugins.get_tools_cwl(config)]   # without it, it is read


@pytest.mark.fast
def test_a_basepath_outside_or_at_a_search_path_hides_nothing(tmp_path: Path) -> None:
    """Only a directory below the search path can be generated output inside it."""
    root = tmp_path / 'root'
    (root / 'a').mkdir(parents=True)
    (root / 'a' / 'a.cwl').write_text(TOOL, encoding='utf-8')
    config = {'search_paths_cwl': {'global': [str(root)]}}
    for basepath in (tmp_path / 'elsewhere', root):
        assert [key.stem for key in sophios.plugins.get_tools_cwl(config, basepath=basepath)] == ['a']


@pytest.mark.fast
def test_the_cli_and_python_write_a_run_to_the_same_places(
        project: Path, monkeypatch: pytest.MonkeyPatch, tmp_path: Path) -> None:
    """The same workflow run with the same base path leaves the same files there and a runner command that
    writes provenance, the summary and the outputs there, from `--basepath` and from `run(basepath=)`."""
    commands: dict[str, str] = {}
    monkeypatch.setattr(run_local, 'generate_run_script', lambda cmdline: commands.update(last=cmdline))
    monkeypatch.setattr(python_runtime.preflight, 'prepare', lambda *_a, **_k: None)

    cli_base, python_base = tmp_path / 'cli out', tmp_path / 'python out'
    _sophios(monkeypatch, '--generate_run_script', '--basepath', str(cli_base))
    from_cli = commands['last']
    (project / 'python').mkdir()
    monkeypatch.chdir(project / 'python')
    Workflow([Step(clt_path=project / 'noop.cwl')], 'w').run(
        basepath=str(python_base), run_args_dict={'generate_run_script': 'yes'})
    from_python = commands['last']

    assert _files(cli_base) == _files(python_base) >= {'w.cwl', 'w_inputs.yml'}
    for base, cmdline in ((cli_base, from_cli), (python_base, from_python)):
        resolved = base.resolve()
        assert f'--provenance {resolved / "provenance" / "w"}' in cmdline
        assert f'--write-summary {resolved / "output_w.json"}' in cmdline
        assert f'--outdir {resolved / "outdir_cwltool_w_"}' in cmdline
    assert not (project / 'autogenerated').exists() and not (project / 'python' / 'autogenerated').exists()
