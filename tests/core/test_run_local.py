@pytest.mark.fast
def test_the_python_api_runs_the_command_its_run_script_holds(monkeypatch: pytest.MonkeyPatch, tmp_path: Path,
                                                              offline: None) -> None:
    """`run()` starts exactly what `run(generate_run_script=yes)` writes to run.sh."""
    del offline
    fake = install(monkeypatch, tmp_path)
    monkeypatch.setattr(backends, 'datetime', _Frozen)
    run_args = {'quiet': 'no', 'cachedir': 'cache', 'logLevel': 'INFO'}
    _echo_workflow().run(run_args_dict={**run_args, 'generate_run_script': 'yes'})
    script = shlex.split((tmp_path / 'run.sh').read_text(encoding='utf-8').splitlines()[-1])
    _echo_workflow().run(run_args_dict=run_args)
    # The stand-in is a script, so its own argv[0] is its path: the arguments are compared.
    assert script[0] == 'cwltool_filterlog' and '--cachedir' in script and '--quiet' not in script
    assert fake.record()['argv'][1:] == script[1:]


class _Frozen(backends.datetime):
    @classmethod
    def now(cls, tz: object = None) -> '_Frozen':
        return cls(2026, 10, 9, 12, 2, 16)


