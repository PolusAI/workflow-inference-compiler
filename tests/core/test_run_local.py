from .fake_runner import POSIX_ONLY, FakeRunner, install

REPO_ROOT = Path(__file__).resolve().parents[2]
HELLOWORLD = REPO_ROOT / 'docs' / 'tutorials' / 'helloworld.wic'

pytestmark = POSIX_ONLY


def _echo_workflow(name: str = 'wf') -> Workflow:
    echo = Step(clt_path=REPO_ROOT / 'cwl_adapters' / 'echo.cwl')
    echo.inputs.message = 'hello'
    return Workflow([echo], name)


@pytest.fixture(name='offline')
def _offline(monkeypatch: pytest.MonkeyPatch, tmp_path: Path) -> None:
    """Run from `tmp_path`, with nothing pulled and no container engine asked."""
    monkeypatch.chdir(tmp_path)
    monkeypatch.setattr(preflight, 'prepare', lambda *_a, **_k: None)


@pytest.fixture(name='sophios')
def _sophios(monkeypatch: pytest.MonkeyPatch, offline: None) -> Callable[..., int]:
    """`sophios --yaml helloworld.wic <flags>`; returns its exit code."""
    del offline

    def run(*flags: str) -> int:
        monkeypatch.setattr('sys.argv', ['sophios', '--yaml', str(HELLOWORLD), *flags])
        try:
            cli.main()
        except SystemExit as stopped:
            return int(stopped.code or 0)
        return 0
    return run


@pytest.mark.fast
def test_the_runner_gets_the_users_variables_and_this_process_keeps_its_own(
        monkeypatch: pytest.MonkeyPatch, tmp_path: Path, offline: None) -> None:
    """A value reaches the runner exactly as given, through its environment and no shell; `os.environ` is
    not touched, so nothing else in the process sees it."""
    del offline
    fake = install(monkeypatch, tmp_path)
    value = "p@ss$word! a&b 'single' \"double\" ;|<>()`x`\nline two"
    monkeypatch.delenv('SOPHIOS_TEST_TOKEN', raising=False)
    _echo_workflow().run(user_env_vars={'SOPHIOS_TEST_TOKEN': value})
    assert fake.record()['env']['SOPHIOS_TEST_TOKEN'] == value
    assert 'SOPHIOS_TEST_TOKEN' not in os.environ


