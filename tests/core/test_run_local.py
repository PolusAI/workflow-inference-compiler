def _interrupt_once_started(fake: FakeRunner) -> threading.Thread:
    """Press Ctrl-C, as a terminal would, once the stand-in runner has started."""
    def press() -> None:
        fake.wait_until_started()
        _thread.interrupt_main()
    thread = threading.Thread(target=press, daemon=True)
    thread.start()
    return thread


@pytest.mark.fast
@pytest.mark.serial
@pytest.mark.parametrize('runner', ['cwltool', 'toil-cwl-runner'])
def test_ctrl_c_stops_the_runner_and_exits_130(monkeypatch: pytest.MonkeyPatch, tmp_path: Path,
                                               sophios: Callable[..., int], capsys: pytest.CaptureFixture[str],
                                               runner: str) -> None:
    """The runner is sent SIGTERM, on which cwltool stops the containers it started, and the CLI exits 130."""
    fake = install(monkeypatch, tmp_path, sleep=60)
    pressed = _interrupt_once_started(fake)
    assert sophios('--run_local', '--cwl_runner', runner) == 130
    pressed.join()
    assert fake.record()['signal'] == 15
    assert "Interrupted; the runner's processes were terminated." in capsys.readouterr().err


@pytest.mark.fast
@pytest.mark.serial
def test_a_runner_that_ignores_sigterm_is_killed_after_the_grace(
        monkeypatch: pytest.MonkeyPatch, tmp_path: Path, offline: None) -> None:
    """Nothing the run started outlives it: the runner and its session are killed when SIGTERM is not enough."""
    del offline
    fake = install(monkeypatch, tmp_path, sleep=60, ignore_sigterm=True)
    monkeypatch.setattr(run_local, 'STOP_GRACE_SECONDS', 0.5)
    handle = run_local.start(RunRequest('wf', tmp_path))
    fake.wait_until_started()
    handle.cancel()
    status = handle.status()
    assert status.state is run_local.RunState.CANCELLED
    assert status.exit_code == -9


@pytest.mark.fast
def test_a_run_cancelled_from_another_thread_ends_cancelled(
        monkeypatch: pytest.MonkeyPatch, tmp_path: Path, capsys: pytest.CaptureFixture[str]) -> None:
    """`wait` reports the cancellation, not the exit status the runner stopped with."""
    monkeypatch.chdir(tmp_path)
    fake = install(monkeypatch, tmp_path, sleep=60)
    handle = run_local.start(RunRequest('wf', tmp_path))
    fake.wait_until_started()
    canceller = threading.Thread(target=handle.cancel)
    canceller.start()
    status = handle.wait()
    canceller.join()
    assert status.state is run_local.RunState.CANCELLED
    assert fake.record()['signal'] == 15
    assert 'Failure!' not in capsys.readouterr().err


@pytest.mark.fast
def test_status_answers_at_once_while_what_the_runner_started_holds_its_output(
        monkeypatch: pytest.MonkeyPatch, tmp_path: Path) -> None:
    """The runner has exited, but a process it left behind keeps its streams open: the run is still RUNNING."""
    monkeypatch.chdir(tmp_path)
    fake = install(monkeypatch, tmp_path, leave_behind=10)
    handle = run_local.start(RunRequest('wf', tmp_path))
    fake.wait_until_started()
    until = time.monotonic() + 1.5
    while time.monotonic() < until:
        asked = time.monotonic()
        assert handle.status().state is run_local.RunState.RUNNING
        assert time.monotonic() - asked < 0.5
        time.sleep(0.1)
    handle.cancel()   # ends what it left behind


